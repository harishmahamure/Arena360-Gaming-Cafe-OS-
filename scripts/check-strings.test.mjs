import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  checkRepo,
  checkSource,
  formatViolation,
  looksLikeProse,
  messageKeys,
  scanStringLiterals,
} from "./check-strings.mjs";

const keys = new Set(["app.name", "surface.hub", "player.balance.insufficient"]);
const lint = (file, text) => checkSource(file, text, keys).map(formatViolation);
const PAGE = "apps/hub/src/routes/+page.svelte";

test("hard-coded text: a svelte text node fails with file:line", () => {
  assert.deepEqual(lint(PAGE, "<div>\n  <p>Printer offline</p>\n</div>\n"), [
    `${PAGE}:2 hard-coded string "Printer offline"`,
  ]);
});

test("ignored: <!-- i18n-ignore --> on the line before exempts it", () => {
  assert.deepEqual(lint(PAGE, "<!-- i18n-ignore -->\n<p>Printer offline</p>\n"), []);
});

test("text without letters passes", () => {
  assert.deepEqual(lint(PAGE, '<p>{t("app.name")} · 42</p>\n'), []);
});

test("literal text attributes fail; other attributes and expressions pass", () => {
  const src = [
    '<img alt="Floor view" src="x.png" />',
    '<input placeholder="Search" class="search box" />',
    '<button aria-label="Close" title={t("app.name")}></button>',
    '<Field label="Name" />',
  ].join("\n");
  assert.deepEqual(lint(PAGE, src), [
    `${PAGE}:1 hard-coded string "Floor view"`,
    `${PAGE}:2 hard-coded string "Search"`,
    `${PAGE}:3 hard-coded string "Close"`,
    `${PAGE}:4 hard-coded string "Name"`,
  ]);
});

test("prose literals in svelte scripts and markup expressions fail", () => {
  const src = [
    '<script lang="ts">',
    '  import { t } from "@arena/ui";',
    '  const msg = "Printer is offline";',
    "</script>",
    '<p>{ok ? "All good here" : t("app.name")}</p>',
  ].join("\n");
  assert.deepEqual(lint(PAGE, src), [
    `${PAGE}:3 hard-coded string "Printer is offline"`,
    `${PAGE}:5 hard-coded string "All good here"`,
  ]);
});

test("TS/JS: prose literals fail; identifiers, keys, paths and specifiers pass", () => {
  const src = [
    'import { thing } from "some package name";',
    'export * from "another package name";',
    'const a = "Printer offline";',
    "const b = 'ok';",
    'const c = "player.login.failure";',
    "const d = `Hello ${name} there`;",
    'const e = "  spaced out words";',
    'const f = "12 items";',
    'const g = /don\'t match this/; // "Not a string either"',
    '/* "Nor this" */',
    'const h = "Reconnecting"; // i18n-ignore',
    'const i = await import("lazy module name");',
  ].join("\n");
  assert.deepEqual(lint("apps/hub/src/lib/x.ts", src), [
    'apps/hub/src/lib/x.ts:3 hard-coded string "Printer offline"',
    'apps/hub/src/lib/x.ts:6 hard-coded string "Hello x there"',
    'apps/hub/src/lib/x.ts:7 hard-coded string "spaced out words"',
  ]);
});

test("looksLikeProse needs a leading letter and at least two words", () => {
  assert.ok(looksLikeProse("Printer offline"));
  assert.ok(looksLikeProse("Reconnecting… now"));
  assert.ok(!looksLikeProse("Printer"));
  assert.ok(!looksLikeProse("12 items"));
  assert.ok(!looksLikeProse("./a b"));
});

test("scanStringLiterals skips comments and regex literals", () => {
  const values = scanStringLiterals('x = a / b; y = /"q"/g; // "c"\nz = "d";').map((l) => l.value);
  assert.deepEqual(values, ["d"]);
});

test("missing key: an unknown t() key fails with file:line", () => {
  assert.deepEqual(lint(PAGE, "<p>{t('app.name')}</p>\n<p>{t('staff.nope')}</p>\n"), [
    `${PAGE}:2 unknown message key staff.nope`,
  ]);
  assert.deepEqual(lint("apps/hub/src/x.ts", 'const s = t("staff.nope");\n'), [
    "apps/hub/src/x.ts:1 unknown message key staff.nope",
  ]);
});

test("messageKeys finds literal keys only, not methods like x.t()", () => {
  assert.deepEqual(
    messageKeys('t("a.b"); t(\'c.d\', {x: 1}); obj.t("e.f"); t(`g`); format("h")').map(
      (k) => k.key,
    ),
    ["a.b", "c.d"],
  );
});

test("a svelte file that does not parse is reported", () => {
  const out = lint(PAGE, "<p>{</p>\n");
  assert.equal(out.length, 1);
  assert.match(out[0], /cannot parse/);
});

test("checkRepo scans apps/*/src and packages/ui/src, skipping generated and messages", () => {
  const root = mkdtempSync(join(tmpdir(), "strings-"));
  try {
    const put = (path, text) => {
      mkdirSync(join(root, path, ".."), { recursive: true });
      writeFileSync(join(root, path), text);
    };
    put("packages/ui/src/messages/en.json", JSON.stringify({ "app.name": "Arena 360" }));
    put("packages/ui/src/messages/index.js", 'throw new Error("unknown message key");\n');
    put("packages/ui/src/generated/AppError.ts", '// "Do not edit this file"\n');
    put("apps/hub/src-tauri/x.js", 'const s = "Not scanned here";\n');
    put("apps/hub/src/routes/+page.svelte", "<h1>{t('app.name')}</h1>\n<p>Printer offline</p>\n");
    assert.deepEqual(checkRepo(root), [
      'apps/hub/src/routes/+page.svelte:2 hard-coded string "Printer offline"',
    ]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("a regex after `return` is not read as a string", () => {
  assert.deepEqual(lint("apps/hub/src/x.ts", 'function f() {\n  return /"a b"/;\n}\n'), []);
});

test("a svelte parse error is reported on its line, not its offset", () => {
  const out = checkSource(PAGE, "<div>\n  <p>ok</p>\n  <p>{</p>\n</div>\n", keys);
  assert.equal(out.length, 1);
  assert.equal(out[0].line, 3);
});

test(".astro files get the unknown-key check only", () => {
  const src =
    '---\nimport { t } from "@arena/ui";\n---\n<title>{t("app.name")}</title>\n<p>Hard coded prose</p>\n<p>{t("staff.nope")}</p>\n';
  assert.deepEqual(lint("apps/marketing/src/pages/index.astro", src), [
    "apps/marketing/src/pages/index.astro:6 unknown message key staff.nope",
  ]);
});

test("only the catalogue's own generated/messages folders are skipped", () => {
  const root = mkdtempSync(join(tmpdir(), "strings-"));
  try {
    const put = (path, text) => {
      mkdirSync(join(root, path, ".."), { recursive: true });
      writeFileSync(join(root, path), text);
    };
    put("packages/ui/src/messages/en.json", JSON.stringify({ "app.name": "Arena 360" }));
    put("packages/ui/src/generated/x.ts", 'const s = "Skipped prose here";\n');
    put("apps/hub/src/generated/x.ts", 'const s = "Hand written prose";\n');
    put("apps/hub/src/messages/y.ts", 'const s = "More hand written prose";\n');
    put("apps/marketing/src/pages/index.astro", '<p>{t("nope.key")}</p>\n');
    assert.deepEqual(checkRepo(root), [
      'apps/hub/src/generated/x.ts:1 hard-coded string "Hand written prose"',
      'apps/hub/src/messages/y.ts:1 hard-coded string "More hand written prose"',
      "apps/marketing/src/pages/index.astro:1 unknown message key nope.key",
    ]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
