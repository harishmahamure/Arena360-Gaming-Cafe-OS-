#!/usr/bin/env node
// Generates the design tokens from the DESIGN.md frontmatter: CSS custom properties
// (`tokens.css`) and typed TS constants (`tokens.ts`), formatted with prettier.
// Output: packages/ui/src/tokens (committed). Reads local files only (no network).

import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

/** The single design source, shared by every token script. */
export const DESIGN_MD =
  "_bmad-output/planning-artifacts/ux-designs/ux-arena-360-final-2026-10-22/DESIGN.md";
export const TOKENS_DIR = "packages/ui/src/tokens";
export const THEMES = ["dark", "hc", "light"];
/** Theme twin suffixes: `<name>-hc`, `<name>-light`. */
export const SUFFIX = { hc: "-hc", light: "-light" };
/** DESIGN.md family name -> CSS font stack (the bundled variable font first). */
export const FONT_FAMILIES = { Sora: '"Sora Variable", "Sora"' };

const HEADER_TEXT =
  "Generated by scripts/gen-tokens.mjs from DESIGN.md. Do not edit; run `pnpm gen:tokens`.";
export const CSS_HEADER = `/* ${HEADER_TEXT} */`;
export const TS_HEADER = `// ${HEADER_TEXT}`;

const REF = /\{([a-z]+)\.([\w-]+)\}/g;
const COLOR_REF = /\{colors\.([\w-]+)\}/g;

/**
 * Dark aliases for names that DESIGN.md only defines as theme twins: the focus ring is
 * `focus-ring-hc` / `focus-ring-light`, and its dark equivalent is the inner ring.
 */
export const DARK_ALIASES = { "focus-ring": "focus-ring-inner" };

/**
 * High-contrast counterparts that do not follow the `X-hc` naming, with the DESIGN.md reason.
 * `null` = the colour is used unchanged in HC.
 */
export const HC_TWINS = {
  // "In HC it is 4px yellow": the two-ring dark focus ring becomes the single focus-ring-hc.
  "focus-ring-inner": "focus-ring-hc",
  "focus-ring-outer": "focus-ring-hc",
};
/** Colours used unchanged in HC (DESIGN.md gives their ratios on hub-tile and on black). */
export const HC_SHARED = /^group-/;

/**
 * The colour a component reference renders as in HC: `X-hc`, a documented twin, the colour
 * itself (already an `-hc` value, or shared), or `null` for a light-only value (no HC use).
 * `undefined` means the HC twin is missing.
 */
export function hcTwin(colors, name) {
  if (name.endsWith(SUFFIX.hc)) return name;
  if (name.endsWith(SUFFIX.light)) return null;
  if (name in HC_TWINS) return HC_TWINS[name];
  if (HC_SHARED.test(name)) return name;
  return `${name}-hc` in colors ? `${name}-hc` : undefined;
}

export const TYPOGRAPHY_FIELDS = ["fontFamily", "fontSize", "fontWeight", "lineHeight"];
const SINGLE_COLOR_REF = /^\{colors\.([\w-]+)\}$/;

/** Parses the YAML frontmatter (between the leading `---` lines) of a Markdown document. */
export function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!m) throw new Error("DESIGN.md: no YAML frontmatter found");
  return parseYaml(m[1]);
}

export function readDesign(root) {
  return parseFrontmatter(readFileSync(join(root, DESIGN_MD), "utf8"));
}

export const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** The theme a colour name belongs to and its base name. */
export function themeOf(name) {
  for (const [theme, suffix] of Object.entries(SUFFIX)) {
    if (name.endsWith(suffix)) return { theme, base: name.slice(0, -suffix.length) };
  }
  return { theme: "dark", base: name };
}

/** Base (dark) colour names, in DESIGN.md order. */
export function baseColorNames(colors) {
  return Object.keys(colors).filter((n) => themeOf(n).theme === "dark");
}

/** The colour name rendered for base name `base` in `theme` (CSS falls back to the dark value). */
export function themedName(colors, base, theme) {
  if (theme === "dark") return base;
  const twin = base + SUFFIX[theme];
  return twin in colors ? twin : base;
}

/** Every `{group.key}` reference in a value, recursively. */
function refsIn(value, path, out) {
  if (typeof value === "string") {
    for (const m of value.matchAll(REF)) out.push({ group: m[1], key: m[2], path });
  } else if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) refsIn(v, `${path}.${k}`, out);
  }
  return out;
}

/**
 * Validates the frontmatter: every `{group.key}` reference resolves, every `{colors.X}` in a
 * component value has an HC twin (see `hcTwin`), and every type ramp has its required fields.
 * @returns {string[]} error messages
 */
export function validate(fm) {
  const errors = [];
  const colors = fm.colors ?? {};
  for (const ref of refsIn(fm.components ?? {}, "components", [])) {
    const group = fm[ref.group];
    if (!group || typeof group !== "object" || !(ref.key in group)) {
      errors.push(`unresolved reference {${ref.group}.${ref.key}} in ${ref.path}`);
    }
  }
  for (const [component, props] of Object.entries(fm.components ?? {})) {
    for (const [prop, value] of Object.entries(props ?? {})) {
      if (typeof value !== "string") continue;
      for (const m of value.matchAll(COLOR_REF)) {
        if (m[1] in colors && hcTwin(colors, m[1]) === undefined) {
          errors.push(
            `missing high-contrast twin: components.${component}.${prop} references ${m[1]}, but colors has no ${m[1]}-hc`,
          );
        }
      }
    }
  }
  for (const [ramp, t] of Object.entries(fm.typography ?? {})) {
    for (const field of TYPOGRAPHY_FIELDS) {
      if (t?.[field] === undefined || t[field] === null || t[field] === "") {
        errors.push(`typography.${ramp} is missing ${field}`);
      }
    }
  }
  return errors;
}

/** Colours that only Hub surfaces use; the Hub is dark + HC only (no light theme). */
export const HUB_ONLY_COLOR = /^(hub|state)-/;

/** Whether a component is Hub-only: it has colour refs and all of them are `hub-*`/`state-*`. */
export function isHubOnlyComponent(props) {
  const refs = refsIn(props ?? {}, "", []).filter((r) => r.group === "colors");
  return refs.length > 0 && refs.every((r) => HUB_ONLY_COLOR.test(r.key));
}

/** Names of the Hub-only components, in DESIGN.md order. */
export function hubOnlyComponents(fm) {
  return Object.entries(fm.components ?? {})
    .filter(([, props]) => isHubOnlyComponent(props))
    .map(([name]) => name);
}

/** Component properties that are a single colour reference. */
export function componentColorTokens(fm) {
  const out = [];
  for (const [component, props] of Object.entries(fm.components ?? {})) {
    const hubOnly = isHubOnlyComponent(props);
    for (const [prop, value] of Object.entries(props ?? {})) {
      const m = typeof value === "string" && value.match(SINGLE_COLOR_REF);
      if (m) out.push({ name: `--${component}-${kebab(prop)}`, color: m[1], hubOnly });
    }
  }
  return out;
}

/** CSS variable for a non-colour `{group.key}` ref; refs without one become a plain identifier. */
const OTHER_REF = { spacing: "space", rounded: "radius", elevation: "elevation" };

/** A DESIGN.md value as CSS: `{colors.X}` -> `var(--color-<colorFor(X)>)`, other refs likewise. */
function cssValue(value, colorFor) {
  return value.replace(REF, (_, group, key) => {
    if (group === "colors") return `var(--color-${colorFor(key)})`;
    if (group in OTHER_REF) return `var(--${OTHER_REF[group]}-${key})`;
    return group === "typography" ? `type-${key}` : key;
  });
}

/**
 * Component properties that contain colour references inside a longer value
 * (e.g. `2px solid {colors.x}`). Each ref becomes `var(--color-X)` (other refs: see `cssValue`);
 * `hc` is the same value with
 * the HC twins, or `null` when a ref is light-only.
 */
export function componentCompoundTokens(fm) {
  const colors = fm.colors ?? {};
  const out = [];
  for (const [component, props] of Object.entries(fm.components ?? {})) {
    for (const [prop, value] of Object.entries(props ?? {})) {
      if (typeof value !== "string" || SINGLE_COLOR_REF.test(value)) continue;
      const refs = [...value.matchAll(COLOR_REF)].map((m) => m[1]);
      if (refs.length === 0) continue;
      const twins = refs.map((r) => hcTwin(colors, r));
      const hc = twins.includes(null) ? null : cssValue(value, (x) => hcTwin(colors, x));
      out.push({ name: `--${component}-${kebab(prop)}`, value: cssValue(value, (x) => x), hc });
    }
  }
  return out;
}

const familyStack = (family) => FONT_FAMILIES[family] ?? `"${family}"`;

/** Builds the CSS text and the list of declared custom property names. */
export function renderCss(fm) {
  const errors = validate(fm);
  if (errors.length > 0) throw new Error(`gen:tokens failed:\n  ${errors.join("\n  ")}`);
  const colors = fm.colors ?? {};
  const names = [];
  const duplicates = [];
  /** A declaration block that fails on a repeated custom property name. */
  const block = (label) => {
    const seen = new Set();
    const lines = [];
    lines.decl = (name, value) => {
      if (seen.has(name)) duplicates.push(`duplicate token ${name} in ${label}`);
      seen.add(name);
      names.push(name);
      lines.push(`  ${name}: ${value};`);
    };
    return lines;
  };
  const bases = baseColorNames(colors);
  const root = block(":root");
  for (const [name, value] of Object.entries(colors)) root.decl(`--color-${name}`, value);
  for (const [key, value] of Object.entries(fm.spacing ?? {})) root.decl(`--space-${key}`, value);
  for (const [key, value] of Object.entries(fm.rounded ?? {})) root.decl(`--radius-${key}`, value);
  for (const [key, value] of Object.entries(fm.elevation ?? {})) {
    root.decl(`--elevation-${key}`, value);
  }
  const classes = [];
  for (const [ramp, t] of Object.entries(fm.typography ?? {})) {
    const v = (prop) => `var(--type-${ramp}-${prop})`;
    root.decl(`--type-${ramp}-family`, familyStack(t.fontFamily));
    root.decl(`--type-${ramp}-size`, t.fontSize);
    root.decl(`--type-${ramp}-weight`, t.fontWeight);
    root.decl(`--type-${ramp}-line-height`, t.lineHeight);
    root.decl(`--type-${ramp}-letter-spacing`, t.letterSpacing ?? "normal");
    const extra = [];
    if (/^uppercase/i.test(t.note ?? "")) extra.push("  text-transform: uppercase;");
    if (/tabular numerals/i.test(t.note ?? "")) extra.push("  font-variant-numeric: tabular-nums;");
    classes.push(
      [
        `.type-${ramp} {`,
        `  font-family: ${v("family")}, system-ui, sans-serif;`,
        `  font-size: ${v("size")};`,
        `  font-weight: ${v("weight")};`,
        `  line-height: ${v("line-height")};`,
        `  letter-spacing: ${v("letter-spacing")};`,
        ...extra,
        "}",
      ].join("\n"),
    );
  }
  // A component token named like a semantic colour alias (`focus-ring.inner` vs the
  // `focus-ring-inner` colour) is not emitted: the alias keeps that name.
  const aliasNames = new Set(
    [
      ...bases,
      ...Object.keys(DARK_ALIASES),
      ...Object.keys(colors).map((n) => themeOf(n).base),
    ].map((n) => `--${n}`),
  );
  const free = (c) => !aliasNames.has(c.name);
  const components = componentColorTokens(fm).filter(free);
  for (const c of components) root.decl(`${c.name}-hc`, `var(--color-${hcTwin(colors, c.color)})`);
  for (const c of componentCompoundTokens(fm).filter(free)) {
    root.decl(c.name, c.value);
    if (c.hc !== null) root.decl(`${c.name}-hc`, c.hc);
  }

  const aliases = (theme) => {
    const out = block(`[data-theme="${theme}"]`);
    for (const b of bases) out.decl(`--${b}`, `var(--color-${themedName(colors, b, theme)})`);
    if (theme === "dark") {
      for (const [alias, name] of Object.entries(DARK_ALIASES)) {
        if (name in colors) out.decl(`--${alias}`, `var(--color-${name})`);
      }
    } else {
      // Names DESIGN.md only defines as twins of this theme (e.g. accent-text-light).
      for (const name of Object.keys(colors)) {
        const t = themeOf(name);
        if (t.theme === theme && !bases.includes(t.base))
          out.decl(`--${t.base}`, `var(--color-${name})`);
      }
    }
    return out;
  };
  const themed = (hubOnly) => {
    const out = block(hubOnly ? "hub-only components" : "components");
    for (const c of components.filter((c) => c.hubOnly === hubOnly)) {
      out.decl(c.name, bases.includes(c.color) ? `var(--${c.color})` : `var(--color-${c.color})`);
    }
    return out;
  };
  const [dark, hc, light, shared, hub] = [
    aliases("dark"),
    aliases("hc"),
    aliases("light"),
    themed(false),
    themed(true),
  ];
  if (duplicates.length > 0) throw new Error(`gen:tokens failed:\n  ${duplicates.join("\n  ")}`);
  const blocks = [
    CSS_HEADER,
    `:root {\n${root.join("\n")}\n}`,
    `/* Semantic aliases: dark ("Cinema Electric") is the default theme. */\n:root,\n[data-theme="dark"] {\n${dark.join("\n")}\n}`,
    `[data-theme="hc"] {\n${hc.join("\n")}\n}`,
    `[data-theme="light"] {\n${light.join("\n")}\n}`,
    `/* Component tokens follow the theme of the element they are used in. */\n:root,\n[data-theme] {\n${shared.join("\n")}\n}`,
    `/* Hub-only components (dark + HC only): no light mapping. */\n:root,\n[data-theme="dark"],\n[data-theme="hc"] {\n${hub.join("\n")}\n}`,
    ...classes,
    `.tabular-nums {\n  font-variant-numeric: tabular-nums;\n}`,
  ];
  return { css: blocks.join("\n\n") + "\n", names: [...new Set(names)] };
}

/** Builds the TS constants module. */
export function renderTs(fm, names) {
  const obj = (name, value) => `export const ${name} = ${JSON.stringify(value ?? {})} as const;`;
  return [
    TS_HEADER,
    obj("colors", fm.colors),
    obj("typography", fm.typography),
    obj("spacing", fm.spacing),
    obj("radius", fm.rounded),
    obj("elevation", fm.elevation),
    obj("components", fm.components),
    `/** Components used only on Hub surfaces (dark + HC only; no light theme). */\nexport const hubOnlyComponents = ${JSON.stringify(hubOnlyComponents(fm))} as const;`,
    `/** Every CSS custom property declared in tokens.css. */\nexport type TokenName =\n${names.map((n) => `  | ${JSON.stringify(n)}`).join("\n")};`,
    "",
  ].join("\n\n");
}

/** Renders both files from frontmatter. Throws on validation errors. */
export function renderTokens(fm) {
  const { css, names } = renderCss(fm);
  return { "tokens.css": css, "tokens.ts": renderTs(fm, names) };
}

/**
 * Runs the full generation in `root`. Writes into a temp folder and replaces the committed
 * folder only when rendering and prettier both succeeded; on failure it is left untouched.
 */
export async function generate(root) {
  const dir = join(root, TOKENS_DIR);
  const files = renderTokens(readDesign(root));
  const tmp = mkdtempSync(join(tmpdir(), "arena-gen-tokens-"));
  try {
    const prettier = await import("prettier");
    for (const [file, source] of Object.entries(files)) {
      const options = (await prettier.resolveConfig(join(dir, file))) ?? {};
      const path = join(tmp, file);
      writeFileSync(path, await prettier.format(source, { ...options, filepath: path }));
    }
    // Swap in the new folder; on any failure the previous one is restored.
    const backup = `${dir}.bak-${process.pid}`;
    const hadDir = existsSync(dir);
    if (hadDir) renameSync(dir, backup);
    try {
      mkdirSync(dir, { recursive: true });
      for (const file of readdirSync(tmp)) copyFileSync(join(tmp, file), join(dir, file));
    } catch (err) {
      rmSync(dir, { recursive: true, force: true });
      if (hadDir) renameSync(backup, dir);
      throw err;
    }
    if (hadDir) rmSync(backup, { recursive: true, force: true });
    return Object.keys(files);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

async function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const files = await generate(root);
  console.log(`gen:tokens: ${files.join(", ")} in ${TOKENS_DIR}`);
}

const isMain = (() => {
  try {
    return (
      Boolean(process.argv[1]) &&
      realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])
    );
  } catch {
    return false;
  }
})();

if (isMain) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
