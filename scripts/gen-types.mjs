#!/usr/bin/env node
// Generates the TypeScript protocol types from `arena-proto` with ts-rs, writes the `index.ts`
// barrel and formats the folder with prettier. The same test run writes `currencies.json` (the
// `arena_proto::currency` table). Output: packages/ui/src/generated (committed).

import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const GENERATED_DIR = "packages/ui/src/generated";
export const HEADER =
  "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.";

/** Type names exported by the ts-rs files in a directory listing (barrel excluded). */
export function typeNamesFromFiles(files) {
  return files
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();
}

/** The `index.ts` barrel re-exporting every generated type. */
export function buildBarrel(names) {
  const body = names.map((n) => `export type { ${n} } from "./${n}";`).join("\n");
  return `${HEADER}\n\n${body}\n`;
}

/** Type names re-exported by a barrel built with `buildBarrel`. */
export function parseBarrel(text) {
  const names = [];
  for (const m of text.matchAll(/export\s+type\s*\{([^}]*)\}\s*from/g)) {
    for (const part of m[1].split(",")) {
      const name = part
        .trim()
        .split(/\s+as\s+/)
        .pop()
        ?.trim();
      if (name) names.push(name);
    }
  }
  return names;
}

/**
 * Runs the full generation in `root`. Exports into a temp folder and replaces the committed
 * folder only when cargo, the barrel and prettier all succeeded; on failure it is left untouched.
 */
export async function generate(root) {
  const dir = join(root, GENERATED_DIR);
  const tmp = mkdtempSync(join(tmpdir(), "arena-gen-types-"));
  try {
    const cargo = spawnSync(
      "cargo",
      ["test", "--locked", "-p", "arena-proto", "--features", "export-ts"],
      {
        cwd: root,
        env: { ...process.env, TS_RS_EXPORT_DIR: tmp },
        stdio: ["ignore", "pipe", "pipe"],
        encoding: "utf8",
      },
    );
    if (cargo.error) throw cargo.error;
    if (cargo.status !== 0) {
      process.stdout.write(cargo.stdout ?? "");
      process.stderr.write(cargo.stderr ?? "");
      throw new Error(`cargo test -p arena-proto --features export-ts exited ${cargo.status}`);
    }

    const names = typeNamesFromFiles(readdirSync(tmp));
    writeFileSync(join(tmp, "index.ts"), buildBarrel(names));

    const prettier = await import("prettier");
    // The TypeScript types and the data tables written next to them (currencies.json).
    for (const file of readdirSync(tmp).filter((f) => f.endsWith(".ts") || f.endsWith(".json"))) {
      const path = join(tmp, file);
      // Resolve config as if the file were already in place so repo settings apply.
      const options = (await prettier.resolveConfig(join(dir, file))) ?? {};
      const source = readFileSync(path, "utf8");
      writeFileSync(path, await prettier.format(source, { ...options, filepath: path }));
    }

    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
    for (const file of readdirSync(tmp)) copyFileSync(join(tmp, file), join(dir, file));
    return names;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

async function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const names = await generate(root);
  console.log(`gen:types: ${names.length} types in ${GENERATED_DIR} (${names.join(", ")})`);
}

const isMain = (() => {
  try {
    return (
      Boolean(process.argv[1]) &&
      realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])
    );
  } catch {
    return false;
  }
})();

if (isMain) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
